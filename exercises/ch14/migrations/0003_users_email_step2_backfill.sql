-- ============================================================================
-- 0003 — 既存行の email を埋める (段階デプロイ Step 2/3)。
-- ============================================================================
-- アプリが新規登録時に email を書き込むようになった後、 過去のレコードを
-- 一括で埋める。 大規模テーブルではトランザクションを分割するのが定石だが、
-- ここでは小さい DB を前提に 1 文で済ませる。
-- ============================================================================

UPDATE users
   SET email = name || '@example.com'
 WHERE email = '';
