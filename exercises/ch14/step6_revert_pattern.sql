-- ============================================================================
-- ch14 / step 6 — 失敗したマイグレーションの「打ち消し」 パターン。
-- ============================================================================
-- 過去番号は<strong>絶対に書き換えない</strong>。 失敗したマイグレーションがあったら、
-- 次の番号で「逆操作」 を流して状態を戻す。 履歴は残る、 状態は前進する。
--
-- 例: 「0005 で誤って evil_column を足してしまった」 を 0006 で取り消す。
-- ============================================================================

-- migrations/0005_add_evil_column.sql  (←失敗例として例示)
--   ALTER TABLE users ADD COLUMN evil_column TEXT;

-- migrations/0006_revert_evil_column.sql  (←打ち消し)
--   ALTER TABLE users DROP COLUMN evil_column;

-- ----------------------------------------------------------------------------
-- なぜ過去番号を書き換えないのか
-- ----------------------------------------------------------------------------
-- (a) 既に他の環境 (ステージング, 同僚のローカル) に流れている可能性がある。
--     書き換えるとそれらの環境とズレが生じ、 schema_migrations の整合性が壊れる。
-- (b) 履歴を残すと「あのときなぜ戻したか」 を将来の自分が追える。
-- (c) 多くのチーム制 / OSS マイグレーションツール (Flyway, golang-migrate) が
--     この方針を採用している。

-- ----------------------------------------------------------------------------
-- 演習
-- ----------------------------------------------------------------------------
